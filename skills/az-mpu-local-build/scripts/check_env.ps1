# check_env.ps1
# MPU 本地构建环境检查脚本
# 用法: powershell -File check_env.ps1 -Workspace "C:\HQ_Workspace\wit803_001-open"

param(
    [string]$Workspace = "C:\HQ_Workspace\wit803_001-open"
)

$ErrorActionPreference = "Stop"
$ContainerName = "sim7805-wit803_001"
$BuildScript = "$Workspace\tools\local_build_mpu\local_build_mpu.bat"
$InternalBuildScript = "/home/sei/autobuild/k3_sim7805/k3_sim7805/build/mpu/build.sh"
$PackagePath = "$Workspace\autobuild\k3_sim7805\k3_sim7805\package\package.zip"

$issues = @()
$warnings = @()

function Write-Check {
    param([string]$Item, [string]$Status, [string]$Detail = "")
    $symbol = if ($Status -eq "OK") { "[OK]" } elseif ($Status -eq "WARN") { "[WARN]" } else { "[FAIL]" }
    Write-Host "$symbol $Item"
    if ($Detail) { Write-Host "    $Detail" }
}

Write-Host "=== MPU Local Build Environment Check ==="
Write-Host "Workspace: $Workspace"
Write-Host ""

# 1. Check Docker
Write-Host "--- Docker ---"
try {
    $dockerVersion = docker --version 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Check "Docker installed" "OK" $dockerVersion
    } else {
        Write-Check "Docker not found" "FAIL"
        $issues += "ERR_DOCKER_NOT_FOUND: Docker is not installed or not in PATH"
    }
} catch {
    Write-Check "Docker check failed" "FAIL" $_.Exception.Message
    $issues += "ERR_DOCKER_NOT_FOUND: Docker command failed"
}

# 2. Check container exists
Write-Host "--- Container ---"
$containerId = docker ps -a -q -f "name=^$ContainerName$" 2>&1
if ($containerId) {
    Write-Check "Container '$ContainerName' exists" "OK" "ID: $containerId"
    $containerShortId = $containerId.Substring(0, [Math]::Min(12, $containerId.Length))
    
    # 3. Check container running
    $running = docker ps -q -f "name=^$ContainerName$" 2>&1
    if ($running) {
        Write-Check "Container is running" "OK"
    } else {
        Write-Check "Container is not running, attempting start..." "WARN"
        $startResult = docker start $ContainerName 2>&1
        if ($LASTEXITCODE -eq 0) {
            Write-Check "Container started successfully" "OK"
        } else {
            Write-Check "Container start failed" "FAIL"
            Write-Host "    Error: $startResult"
            
            # Check for port conflict
            if ($startResult -match "port is already allocated") {
                $issues += "ERR_PORT_CONFLICT: Port 127.0.0.1:2023 is already in use"
                Write-Host "    Checking port 2023..."
                $portCheck = netstat -ano | Select-String ":2023 "
                if ($portCheck) {
                    Write-Host "    Port usage: $portCheck"
                }
                Write-Host "    Other containers:"
                docker ps -a --format "table {{.Names}}\t{{.Status}}\t{{.Ports}}" | Select-String "2023"
            } else {
                $issues += "ERR_CONTAINER_NOT_RUNNING: Container $ContainerName failed to start"
            }
        }
    }
} else {
    Write-Check "Container '$ContainerName' not found" "FAIL"
    $issues += "ERR_CONTAINER_NOT_FOUND: Container does not exist, run ctp_docker_run.bat"
}

# 4. Check build script
Write-Host "--- Build Script ---"
if (Test-Path $BuildScript) {
    Write-Check "local_build_mpu.bat exists" "OK" $BuildScript
} else {
    Write-Check "local_build_mpu.bat missing" "FAIL" $BuildScript
    $issues += "ERR_BUILD_SCRIPT_MISSING: $BuildScript not found"
}

# 5. Check container internal build script
if ($containerId -and $running) {
    $check = docker exec $ContainerName test -f $InternalBuildScript 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Check "Container build.sh exists" "OK" $InternalBuildScript
    } else {
        Write-Check "Container build.sh missing" "FAIL" $InternalBuildScript
        $issues += "ERR_BUILD_SCRIPT_MISSING: Container internal $InternalBuildScript not found"
    }
}

# 6. Check package baseline
Write-Host "--- Package ---"
if (Test-Path $PackagePath) {
    $pkgInfo = Get-Item $PackagePath
    $sizeMB = [math]::Round($pkgInfo.Length / 1MB, 1)
    Write-Check "package.zip exists" "OK" "Size: ${sizeMB}MB, Modified: $($pkgInfo.LastWriteTime)"
    Write-Host "    (Will compare timestamp after build to verify update)"
} else {
    Write-Check "package.zip not found" "WARN" "Will be generated by build"
}

# Summary
Write-Host ""
Write-Host "=== Summary ==="
if ($issues.Count -eq 0) {
    Write-Host "[OK] Environment is ready for MPU local build."
    Write-Host "[INFO] Pre-build package status saved for comparison."
    exit 0
} else {
    Write-Host "[FAIL] Found $($issues.Count) issue(s):"
    foreach ($issue in $issues) {
        Write-Host "  - $issue"
    }
    exit 1
}
