param(
    [string]$WorkspacePath = (Get-Location).Path,
    [string]$ProjectFile = "",
    [string]$TargetName = "",
    [string]$Uv4Path = "",
    [string]$BuildCommand = "",
    [string]$BuildScriptPath = "build_keil.bat",
    [string]$LogFile = "",
    [switch]$InitBuildScript,
    [switch]$Rebuild,
    [switch]$BuildOnly,
    [switch]$ResolveOnly
)

$ErrorActionPreference = "Stop"

function Resolve-AbsolutePath {
    param(
        [string]$BasePath,
        [string]$Path
    )

    $resolved = $Path
    if (-not [System.IO.Path]::IsPathRooted($Path)) {
        $resolved = Join-Path $BasePath $Path
    }

    [System.IO.Path]::GetFullPath($resolved)
}

function Resolve-Uv4Path {
    param([string]$ConfiguredPath)

    $candidates = @()
    if (-not [string]::IsNullOrWhiteSpace($ConfiguredPath)) {
        $candidates += $ConfiguredPath
    }
    if (-not [string]::IsNullOrWhiteSpace($env:KEIL_UV4_PATH)) {
        $candidates += $env:KEIL_UV4_PATH
    }

    $command = Get-Command "UV4.exe" -ErrorAction SilentlyContinue
    if ($null -ne $command) {
        $candidates += $command.Source
    }

    $candidates += @(
        "C:\ProgramData\Keil_v523\UV4\UV4.exe",
        "C:\ProgramData\Keil_v5\UV4\UV4.exe",
        "C:\Keil_v5\UV4\UV4.exe",
        "C:\Keil\UV4\UV4.exe",
        "C:\Keil_v5\UV4.exe"
    )

    foreach ($candidate in $candidates) {
        if (Test-Path $candidate) {
            return (Resolve-Path $candidate).Path
        }
    }

    throw "ERR_KEIL_NOT_AVAILABLE: UV4.exe was not found"
}

function Get-RelativePathForBatch {
    param(
        [string]$BasePath,
        [string]$TargetPath
    )

    $baseFullPath = [System.IO.Path]::GetFullPath($BasePath).TrimEnd('\') + '\'
    $targetFullPath = [System.IO.Path]::GetFullPath($TargetPath)
    if ($targetFullPath.StartsWith($baseFullPath, [System.StringComparison]::OrdinalIgnoreCase)) {
        return $targetFullPath.Substring($baseFullPath.Length)
    }

    $targetFullPath
}

function New-KeilBuildScript {
    param(
        [string]$WorkspacePath,
        [string]$ScriptPath,
        [string]$ProjectPath,
        [string]$TargetName,
        [string]$LogFile
    )

    $resolvedScriptPath = Resolve-AbsolutePath -BasePath $WorkspacePath -Path $ScriptPath
    if (Test-Path $resolvedScriptPath) {
        return [ordered]@{
            created = $false
            path = $resolvedScriptPath
            message = "build script already exists; not overwritten"
        }
    }

    $scriptDir = Split-Path -Parent $resolvedScriptPath
    if (-not (Test-Path $scriptDir)) {
        New-Item -ItemType Directory -Force $scriptDir | Out-Null
    }

    $relativeProject = Get-RelativePathForBatch -BasePath $scriptDir -TargetPath $ProjectPath
    $relativeLog = Get-RelativePathForBatch -BasePath $scriptDir -TargetPath $LogFile
    $batchProject = $relativeProject
    if (-not [System.IO.Path]::IsPathRooted($relativeProject)) {
        $batchProject = "%~dp0$relativeProject"
    }
    $batchLog = $relativeLog
    if (-not [System.IO.Path]::IsPathRooted($relativeLog)) {
        $batchLog = "%~dp0$relativeLog"
    }
    $targetSwitch = ""
    if (-not [string]::IsNullOrWhiteSpace($TargetName)) {
        $targetSwitch = ' -t "%TARGET_NAME%"'
    }

    $content = @"
@echo off
setlocal EnableExtensions
REM Generated by az-keil-build. Fill UV4_EXE_FULL_PATH before first use.
set "UV4_EXE_FULL_PATH=PLEASE_FILL_UV4_EXE_FULL_PATH"
set "PROJECT_FILE=$batchProject"
set "TARGET_NAME=$TargetName"
set "BUILD_LOG=$batchLog"

if not exist "%UV4_EXE_FULL_PATH%" (
  echo UV4.exe not found: %UV4_EXE_FULL_PATH%
  echo Please edit this file and set UV4_EXE_FULL_PATH to your Keil UV4.exe path.
  exit /b 2
)

"%UV4_EXE_FULL_PATH%" -j0 -r "%PROJECT_FILE%"$targetSwitch -o "%BUILD_LOG%"
set BUILD_RESULT=%errorlevel%
if exist "%BUILD_LOG%" type "%BUILD_LOG%"
exit /b %BUILD_RESULT%
"@

    Set-Content -LiteralPath $resolvedScriptPath -Value $content -Encoding ASCII

    [ordered]@{
        created = $true
        path = $resolvedScriptPath
        message = "created build script; fill UV4_EXE_FULL_PATH before first use"
    }
}

function Resolve-ProjectFile {
    param(
        [string]$WorkspacePath,
        [string]$ProjectFile
    )

    if (-not [string]::IsNullOrWhiteSpace($ProjectFile)) {
        $resolved = Resolve-AbsolutePath -BasePath $WorkspacePath -Path $ProjectFile
        if (-not (Test-Path $resolved)) {
            throw "ERR_PROJECT_FILE_MISSING: $resolved"
        }
        return $resolved
    }

    $projects = Get-ChildItem -Path $WorkspacePath -Recurse -File -Include "*.uvprojx" -ErrorAction SilentlyContinue
    if ($projects.Count -eq 1) {
        return $projects[0].FullName
    }
    elseif ($projects.Count -gt 1) {
        throw "ERR_PROJECT_AMBIGUOUS: multiple .uvprojx files found; pass -ProjectFile"
    }

    return $null
}

function Get-KeilProjectInfo {
    param(
        [string]$ProjectPath,
        [string]$TargetName
    )

    if ([string]::IsNullOrWhiteSpace($ProjectPath)) {
        return $null
    }

    [xml]$projectXml = Get-Content -Raw -Encoding UTF8 $ProjectPath
    $targets = @($projectXml.Project.Targets.Target)
    if ($targets.Count -eq 0) {
        throw "ERR_TARGET_NOT_FOUND: no Target nodes in $ProjectPath"
    }

    $target = $null
    if ([string]::IsNullOrWhiteSpace($TargetName)) {
        $target = $targets[0]
        $TargetName = [string]$target.TargetName
    }
    else {
        $target = $targets | Where-Object { [string]$_.TargetName -eq $TargetName } | Select-Object -First 1
    }

    if ($null -eq $target) {
        throw "ERR_TARGET_NOT_FOUND: $TargetName"
    }

    $projectDir = Split-Path -Parent $ProjectPath
    $common = $target.TargetOption.TargetCommonOption
    $outputDirectory = [string]$common.OutputDirectory
    $outputName = [string]$common.OutputName
    if ([string]::IsNullOrWhiteSpace($outputName)) {
        $outputName = [System.IO.Path]::GetFileNameWithoutExtension($ProjectPath)
    }
    if ([string]::IsNullOrWhiteSpace($outputDirectory)) {
        $outputDirectory = ".\"
    }

    $outputDirAbs = Resolve-AbsolutePath -BasePath $projectDir -Path $outputDirectory
    $createExecutable = ([string]$common.CreateExecutable) -eq "1"
    $createHexFile = ([string]$common.CreateHexFile) -eq "1"
    $createLib = ([string]$common.CreateLib) -eq "1"

    $axf = $null
    $hex = $null
    $lib = $null
    if ($createExecutable) {
        $axf = Join-Path $outputDirAbs ($outputName + ".axf")
    }
    if ($createHexFile) {
        $hex = Join-Path $outputDirAbs ($outputName + ".hex")
    }
    if ($createLib) {
        $lib = Join-Path $outputDirAbs ($outputName + ".lib")
    }

    $postBuildOutputs = @()
    $afterMake = $common.AfterMake
    if ($null -ne $afterMake) {
        $userPrograms = @([string]$afterMake.UserProg1Name, [string]$afterMake.UserProg2Name)
        foreach ($userProgram in $userPrograms) {
            if ($userProgram -match '--output=("[^"]+"|\S+)') {
                $postBuildOutput = $Matches[1].Trim('"')
                $postBuildOutputs += (Resolve-AbsolutePath -BasePath $projectDir -Path $postBuildOutput)
            }
        }
    }

    $binFiles = @()
    $artifactFiles = @()
    if (Test-Path $outputDirAbs) {
        $outputFiles = @(Get-ChildItem -Path $outputDirAbs -File -ErrorAction SilentlyContinue)
        $binFiles = @($outputFiles | Where-Object { $_.Extension -ieq ".bin" } | ForEach-Object { $_.FullName })
        $artifactFiles = @($outputFiles | Where-Object { @(".axf", ".hex", ".bin", ".elf") -contains $_.Extension.ToLowerInvariant() } | ForEach-Object { $_.FullName })
    }
    foreach ($postBuildOutput in $postBuildOutputs) {
        if (Test-Path $postBuildOutput) {
            $extension = [System.IO.Path]::GetExtension($postBuildOutput).ToLowerInvariant()
            if ($extension -eq ".bin") {
                $binFiles += $postBuildOutput
            }
            if (@(".axf", ".hex", ".bin", ".elf") -contains $extension) {
                $artifactFiles += $postBuildOutput
            }
        }
    }

    $binFiles = @($binFiles | Select-Object -Unique)
    $artifactFiles = @($artifactFiles | Select-Object -Unique)

    [ordered]@{
        project_file = $ProjectPath
        project_dir = $projectDir
        target_name = $TargetName
        output_directory = $outputDirAbs
        output_name = $outputName
        create_executable = $createExecutable
        create_hex_file = $createHexFile
        axf_file = $axf
        hex_file = $hex
        lib_file = $lib
        post_build_outputs = $postBuildOutputs
        bin_files = $binFiles
        artifact_files = $artifactFiles
    }
}

function Get-KeilSummary {
    param([string]$LogFile)

    $summary = Select-String -Path $LogFile -Pattern 'Error\(s\),.*Warning\(s\)' | Select-Object -Last 1
    if ($null -eq $summary) {
        throw "ERR_SUMMARY_MISSING: no Keil summary line found in $LogFile"
    }

    $line = $summary.Line.Trim()
    if ($line -match '([0-9]+)\s+Error\(s\),\s+([0-9]+)\s+Warning\(s\)') {
        return [ordered]@{
            summary = $line
            errors = [int]$Matches[1]
            warnings = [int]$Matches[2]
        }
    }

    throw "ERR_SUMMARY_PARSE_FAILED: $line"
}

Push-Location $WorkspacePath
try {
    $workspaceFullPath = (Get-Location).Path
    $resolvedProject = Resolve-ProjectFile -WorkspacePath $workspaceFullPath -ProjectFile $ProjectFile
    $projectInfo = Get-KeilProjectInfo -ProjectPath $resolvedProject -TargetName $TargetName

    if ([string]::IsNullOrWhiteSpace($LogFile)) {
        if ($null -ne $resolvedProject) {
            $LogFile = Join-Path (Split-Path -Parent $resolvedProject) "__build\keil_build.log"
        }
        else {
            $LogFile = "build_keil.log"
        }
    }
    $resolvedLogFile = Resolve-AbsolutePath -BasePath $workspaceFullPath -Path $LogFile

    $result = [ordered]@{
        status = "error"
        timestamp = (Get-Date -Format "yyyy-MM-dd HH:mm:ss")
        mode = $null
        build_command = $null
        build_script = $(if (Get-Variable -Name result -ErrorAction SilentlyContinue) { $result.build_script } else { $null })
        project = $projectInfo
        log_file = $resolvedLogFile
        errors = $null
        warnings = $null
        summary = $null
        error = $null
    }

    if (($InitBuildScript) -and ($null -ne $resolvedProject)) {
        $result.mode = "init-build-script"
        $result.build_script = New-KeilBuildScript -WorkspacePath $workspaceFullPath -ScriptPath $BuildScriptPath -ProjectPath $resolvedProject -TargetName $projectInfo.target_name -LogFile $resolvedLogFile
        $result.status = "success"
        $result | ConvertTo-Json -Depth 8
        return
    }

    if ($ResolveOnly) {
        $result.status = "success"
        $result.mode = "resolve-only"
        $result | ConvertTo-Json -Depth 8
        return
    }

    $beforeWriteTime = $null
    if (Test-Path $resolvedLogFile) {
        $beforeWriteTime = (Get-Item $resolvedLogFile).LastWriteTimeUtc
    }

    if ($null -ne $resolvedProject) {
        try {
            $resolvedUv4 = Resolve-Uv4Path -ConfiguredPath $Uv4Path
        }
        catch {
            $result.mode = "uv4-bootstrap-required"
            $result.build_script = New-KeilBuildScript -WorkspacePath $workspaceFullPath -ScriptPath $BuildScriptPath -ProjectPath $resolvedProject -TargetName $projectInfo.target_name -LogFile $resolvedLogFile
            throw "ERR_UV4_PATH_REQUIRED: UV4.exe was not found. Edit $($result.build_script['path']) and fill UV4_EXE_FULL_PATH, or pass -Uv4Path, or set KEIL_UV4_PATH."
        }
        $logDir = Split-Path -Parent $resolvedLogFile
        if (-not (Test-Path $logDir)) {
            New-Item -ItemType Directory -Force $logDir | Out-Null
        }

        $buildSwitch = "-r"
        if ($BuildOnly -and (-not $Rebuild)) {
            $buildSwitch = "-b"
        }

        $args = @("-j0", $buildSwitch, $resolvedProject)
        if (-not [string]::IsNullOrWhiteSpace($projectInfo.target_name)) {
            $args += @("-t", $projectInfo.target_name)
        }
        $args += @("-o", $resolvedLogFile)

        $result.mode = "uv4-project"
        $result.build_command = "$resolvedUv4 $($args -join ' ')"
        $process = Start-Process -FilePath $resolvedUv4 -ArgumentList $args -Wait -PassThru -WindowStyle Hidden
        if ($process.ExitCode -ne 0) {
            throw "ERR_KEIL_BUILD_FAILED: UV4.exe exited with code $($process.ExitCode)"
        }
    }
    else {
        if ([string]::IsNullOrWhiteSpace($BuildCommand)) {
            $BuildCommand = ".\build_keil.bat"
        }
        if (-not (Test-Path $BuildCommand)) {
            throw "ERR_BUILD_SCRIPT_MISSING: $BuildCommand"
        }

        $result.mode = "build-command"
        $result.build_command = $BuildCommand
        & $BuildCommand
    }

    if (-not (Test-Path $resolvedLogFile)) {
        throw "ERR_LOG_MISSING: $resolvedLogFile"
    }

    $afterWriteTime = (Get-Item $resolvedLogFile).LastWriteTimeUtc
    if (($null -ne $beforeWriteTime) -and ($afterWriteTime -le $beforeWriteTime)) {
        throw "ERR_STALE_LOG: $resolvedLogFile was not updated by the build command"
    }

    $parsed = Get-KeilSummary -LogFile $resolvedLogFile
    $result.summary = $parsed.summary
    $result.errors = $parsed.errors
    $result.warnings = $parsed.warnings

    if ($null -ne $resolvedProject) {
        $result.project = Get-KeilProjectInfo -ProjectPath $resolvedProject -TargetName $projectInfo.target_name
    }

    if (($result.errors -eq 0) -and ($result.warnings -eq 0)) {
        $result.status = "success"
    }
    elseif ($result.errors -gt 0) {
        $result.error = [ordered]@{
            code = "ERR_COMPILE_ERRORS_REMAIN"
            message = $result.summary
        }
    }
    else {
        $result.error = [ordered]@{
            code = "ERR_WARNINGS_REMAIN"
            message = $result.summary
        }
    }

    $result | ConvertTo-Json -Depth 4
}
catch {
    $failure = [ordered]@{
        status = "error"
        timestamp = (Get-Date -Format "yyyy-MM-dd HH:mm:ss")
        build_command = $BuildCommand
        project_file = $ProjectFile
        log_file = $LogFile
        build_script = $null
        error = [ordered]@{
            code = (($_.Exception.Message -split ':')[0])
            message = $_.Exception.Message
        }
    }

    $failure | ConvertTo-Json -Depth 4
    exit 1
}
finally {
    Pop-Location
}
