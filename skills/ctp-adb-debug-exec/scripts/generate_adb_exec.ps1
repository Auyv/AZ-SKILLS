param(
    [string]$Workspace = "C:\HQ_Workspace\YLB04_A6",
    [string]$AppName = "",
    [string]$DevicePath = "/media/card",
    [string]$LdLibraryPath = "/vendor/app/hq/lib",
    [string]$MpuDir = "code\task-jpz_dev\mpu",
    [switch]$Execute
)

$ErrorActionPreference = "Stop"

function Fail($Code, $Message) {
    Write-Error "$Code`: $Message"
    exit 1
}

if ([string]::IsNullOrWhiteSpace($AppName)) {
    Fail "ERR_APP_NAME_EMPTY" "AppName is required."
}

if (-not (Test-Path -LiteralPath $Workspace -PathType Container)) {
    Fail "ERR_WORKSPACE_NOT_FOUND" "Workspace not found: $Workspace"
}

$mpuDir = Join-Path $Workspace $MpuDir
$buildArtifact = Join-Path $mpuDir "build_output\app\debug\$AppName"
if (-not (Test-Path -LiteralPath $buildArtifact -PathType Leaf)) {
    Write-Warning "Build artifact not found (you may need to build first via ctp-mpu-debug-build): $buildArtifact"
}

$safeAppName = $AppName -replace '[^A-Za-z0-9_.-]', '_'
$batScriptPath = Join-Path $mpuDir "adb_exec_$safeAppName.bat"

# Use single-quoted here-string so PowerShell does NOT expand $LD_LIBRARY_PATH inside
# the template. Placeholders are __APP_NAME__, __TEST_PATH__, __LD_PATH__, __DATE__, __TIMESTAMP__.
$template = @'
::/**
:: * @file        adb_exec___APP_NAME__.bat
:: * @brief       adb push and execute __APP_NAME__ on device
:: * @note        Derived from adb_push_app.bat (mcud push+exec template).
:: * @author      Mavis (based on adb_push_app.bat)
:: * @date        __DATE__
:: * @version     1.0
::
:: * @par         修改日志
:: * <table>
:: * <tr><th>Date         <th>Version     <th>Author      <th> Description
:: * <tr><td>__DATE__   <td>1.0         <td>Mavis       <td> 从 adb_push_app.bat 抽出 __APP_NAME__ 专用版本
:: * @copyright   xxxx
:: */

@echo off
:: ============================= Parse arguments ================================

set ARGV_LEN=%#
::echo "There are %ARGV_LEN% arguments passed to the adb_exec___APP_NAME__.bat"

set i=1
:show_argument
if %i% gtr %ARGV_LEN% goto end_show_argument

set arg=!%i%!
::echo "Argument %i%: %arg%"

set /a i+=1
goto show_argument

:end_show_argument
::echo "All arguments printed"

:: Script directory
set SCRIPT_DIR=%~dp0
echo "SCRIPT_DIR=%SCRIPT_DIR%"
:: Current working directory
set CURRENT_DIR=%cd%
echo "CURRENT_DIR=%CURRENT_DIR%"

:: ============================= Run adb debug exec ================================
echo "============= BIGEN: adb_exec___APP_NAME__.bat ============="

set APP_NAME=__APP_NAME__
set TEST_PATH=__TEST_PATH__
set LD_PATH=__LD_PATH__
echo ==========================================================
adb shell "rm -rf %TEST_PATH%/%APP_NAME%"
adb push  "%SCRIPT_DIR%/build_output/app/debug/%APP_NAME%"  "%TEST_PATH%"
adb shell "chmod 777 %TEST_PATH%/%APP_NAME%"

adb shell "export LD_LIBRARY_PATH=%LD_PATH%:$LD_LIBRARY_PATH && %TEST_PATH%/%APP_NAME%"

@REM adb shell sync
echo "============= END: adb_exec___APP_NAME__.bat ============="
echo "adb_exec___APP_NAME__.bat return errorlevel:%errorlevel%"

pause
:: Generated by ctp-adb-debug-exec on __TIMESTAMP__
'@

$dateStr = Get-Date -Format "yyyy/MM/dd"
$timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"

$batScript = $template `
    -replace '__APP_NAME__', $AppName `
    -replace '__TEST_PATH__', $DevicePath `
    -replace '__LD_PATH__', $LdLibraryPath `
    -replace '__DATE__', $dateStr `
    -replace '__TIMESTAMP__', $timestamp

# .bat must use GBK (CP936) encoding + CRLF line endings so cmd.exe parses it on
# Chinese Windows correctly. UTF-8 (no BOM) would leave the Chinese comments in
# the header broken under the default cmd code page.
# Normalize: drop stray CR, then prepend CR before every LF. Pure byte operation,
# no encoding conversion.
$batBytes = [System.Text.Encoding]::GetEncoding(936).GetBytes($batScript)
$batOut = New-Object System.Collections.Generic.List[byte]
foreach ($b in $batBytes) {
    if ($b -eq 0x0A) {
        $batOut.Add(0x0D)
        $batOut.Add(0x0A)
    } elseif ($b -ne 0x0D) {
        $batOut.Add($b)
    }
}
[System.IO.File]::WriteAllBytes($batScriptPath, $batOut.ToArray())

Write-Host "Generated adb script: $batScriptPath"
Write-Host "  AppName:        $AppName"
Write-Host "  DevicePath:     $DevicePath"
Write-Host "  LdLibraryPath:  $LdLibraryPath"
Write-Host "  MpuDir:         $MpuDir"

if ($Execute) {
    Write-Host "Executing adb script (device must be connected via adb)..."
    & cmd.exe /c "\"$batScriptPath\""
    $exitCode = $LASTEXITCODE
    Write-Host "ExitCode: $exitCode"
    exit $exitCode
}
